import Foundation
import Testing
@testable import InventoryServices

/// Pixels in the stored image, which is what the file size tracks.
private func megapixels(_ size: PixelSize?, _ fallback: Double) -> Double {
    size.map { Double($0.width * $0.height) / 1_000_000 } ?? fallback
}

/// Port of `src/services/capture/__tests__/imageScaling.test.ts`.
@Suite("scaleToFit")
struct ImageScalingTests {
    @Test("bounds the longer edge of a portrait photo, not its width")
    func boundsPortraitLongerEdge() throws {
        // The regression this exists for: `resize({ width: 1600 })` left a portrait photo 1600
        // wide and 2133 tall.
        let target = try #require(ImageScaling.scaleToFit(width: 3024, height: 4032, maxEdge: 1400))

        #expect(target == PixelSize(width: 1050, height: 1400))
        #expect(target.longestEdge == 1400)
    }

    @Test("bounds the longer edge of a landscape photo")
    func boundsLandscapeLongerEdge() throws {
        let target = try #require(ImageScaling.scaleToFit(width: 4032, height: 3024, maxEdge: 1400))

        #expect(target == PixelSize(width: 1400, height: 1050))
        #expect(target.longestEdge == 1400)
    }

    @Test("preserves aspect ratio in both orientations")
    func preservesAspectRatio() throws {
        let portrait = try #require(ImageScaling.scaleToFit(width: 3024, height: 4032, maxEdge: 1400))
        let landscape = try #require(ImageScaling.scaleToFit(width: 4032, height: 3024, maxEdge: 1400))

        // Jest's toBeCloseTo(_, 3): |difference| < 0.0005.
        #expect(abs(Double(portrait.width) / Double(portrait.height) - 3024.0 / 4032.0) < 0.0005)
        #expect(abs(Double(landscape.width) / Double(landscape.height) - 4032.0 / 3024.0) < 0.0005)
    }

    @Test("leaves an image that already fits completely alone")
    func leavesFittingImageAlone() {
        // Nil rather than an identity resize: re-scaling to the same size would still cost a
        // resample.
        #expect(ImageScaling.scaleToFit(width: 800, height: 600, maxEdge: 1400) == nil)
        #expect(ImageScaling.scaleToFit(width: 1400, height: 1400, maxEdge: 1400) == nil)
    }

    @Test("never enlarges a small import", arguments: [(320, 240), (240, 320), (1399, 20), (1, 1)])
    func neverEnlarges(width: Int, height: Int) {
        // A screenshot or a received image. Upscaling adds bytes and no detail.
        #expect(ImageScaling.scaleToFit(width: width, height: height, maxEdge: ImageScaling.maxImageDimension) == nil)
    }

    @Test("keeps a pathologically thin image at least one pixel wide")
    func keepsThinImageAtLeastOnePixel() throws {
        let target = try #require(ImageScaling.scaleToFit(width: 20_000, height: 3, maxEdge: 1400))

        #expect(target.width == 1400)
        #expect(target.height >= 1)
    }

    @Test("cuts a portrait photo to well under half the pixels the old bound kept")
    func cutsPixelsByMoreThanHalf() {
        // What the width bound produced, versus what the long-edge bound produces.
        let old = PixelSize(width: 1600, height: Int((4032.0 * 1600 / 3024).rounded(.toNearestOrAwayFromZero)))
        let now = ImageScaling.scaleToFit(width: 3024, height: 4032, maxEdge: ImageScaling.maxImageDimension)

        // Jest's toBeCloseTo(_, 1): |difference| < 0.05.
        #expect(abs(megapixels(old, 0) - 3.41) < 0.05)
        #expect(abs(megapixels(now, 0) - 1.47) < 0.05)
        // JPEG/WebP size tracks pixel count closely, so this is most of the saving.
        #expect(megapixels(now, 0) < megapixels(old, 0) / 2)
    }

    @Test("produces a thumbnail small enough to be worth having")
    func thumbnailIsWorthHaving() throws {
        let thumb = try #require(ImageScaling.scaleToFit(width: 3024, height: 4032, maxEdge: ImageScaling.thumbnailDimension))

        #expect(thumb.longestEdge == ImageScaling.thumbnailDimension)
        // A 64 pt row at 3x needs 192 px; 320 leaves headroom without approaching the cost of
        // decoding the full image.
        #expect(ImageScaling.thumbnailDimension >= 192)
        #expect(megapixels(thumb, 0) < megapixels(
            ImageScaling.scaleToFit(width: 3024, height: 4032, maxEdge: ImageScaling.maxImageDimension), 0) / 15)
    }
}

/// `scaleToFit` and the constants against vectors generated by the real TypeScript
/// (`Fixtures/images/scale-to-fit.json`), including exact `.5` products, which pin JS
/// `Math.round`'s half-up rule.
@Suite("scaleToFit parity with imageScaling.ts")
struct ImageScalingParityTests {
    struct Vectors: Decodable {
        struct Constants: Decodable {
            let MAX_IMAGE_DIMENSION: Int
            let IMAGE_QUALITY: Double
            let THUMBNAIL_DIMENSION: Int
            let THUMBNAIL_QUALITY: Double
        }
        let constants: Constants
        /// `[width, height, maxEdge, targetWidth | null, targetHeight | null]`
        let vectors: [[Int?]]
    }

    static func load() throws -> Vectors {
        try JSONDecoder().decode(Vectors.self, from: ImageFixtures.data("scale-to-fit.json"))
    }

    @Test("the sizing constants match imageScaling.ts")
    func constants() throws {
        let constants = try Self.load().constants
        #expect(ImageScaling.maxImageDimension == constants.MAX_IMAGE_DIMENSION)
        #expect(ImageScaling.imageQuality == constants.IMAGE_QUALITY)
        #expect(ImageScaling.thumbnailDimension == constants.THUMBNAIL_DIMENSION)
        #expect(ImageScaling.thumbnailQuality == constants.THUMBNAIL_QUALITY)
    }

    @Test("every vector matches the TypeScript")
    func vectors() throws {
        let vectors = try Self.load().vectors
        #expect(vectors.count > 2000)
        var mismatches: [String] = []
        for vector in vectors {
            let width = try #require(vector[0]), height = try #require(vector[1]), edge = try #require(vector[2])
            let expected = vector[3].flatMap { w in vector[4].map { PixelSize(width: w, height: $0) } }
            let actual = ImageScaling.scaleToFit(width: width, height: height, maxEdge: edge)
            if actual != expected {
                mismatches.append("\(width)×\(height) → \(edge): \(String(describing: actual)) ≠ \(String(describing: expected))")
            }
        }
        #expect(mismatches.isEmpty, "\(mismatches.prefix(20))")
    }

    @Test("an exact half rounds up, like JS Math.round", arguments: [
        // 2800 → 1400 halves every edge: 1001 × 0.5 = 500.5 → 501.
        (2800, 1001, 1400, PixelSize(width: 1400, height: 501)),
        (1001, 2800, 1400, PixelSize(width: 501, height: 1400)),
        // Even integer parts tell half-up from half-even: 2.5 → 3, not 2.
        (640, 5, 320, PixelSize(width: 320, height: 3)),
        (5600, 10, 1400, PixelSize(width: 1400, height: 3)),
    ])
    func halfRoundsUp(width: Int, height: Int, edge: Int, expected: PixelSize) {
        #expect(ImageScaling.scaleToFit(width: width, height: height, maxEdge: edge) == expected)
    }
}
