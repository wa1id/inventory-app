/// A fresh in-memory database migrated to the latest version (RN `freshRepos`).
func freshRepos(environment: RepositoryEnvironment = .live) throws -> LocalRepositories {
    let store = try DatabaseStore.inMemory()
    try store.migrate()
    return LocalRepositories(store: store, environment: environment)
}

/// Repositories over an existing store, without migrating (RN `createRepositories`).
func repositories(_ store: DatabaseStore, environment: RepositoryEnvironment = .live) -> LocalRepositories {
    LocalRepositories(store: store, environment: environment)
}

/// RN `seedSpaceAndContainer`: a Garage space with one box.
@discardableResult
func seedSpaceAndContainer(_ repos: LocalRepositories) async throws -> (space: Space, container: Container) {
    let space = try await repos.spaces.create(CreateSpaceInput(name: "Garage", icon: "car", color: "#5B8DEF"))
    let container = try await repos.containers.create(CreateContainerInput(spaceId: space.id, visualType: .box))
    return (space, container)
}

/// RN `expectCount`: `SELECT COUNT(*)` of a table.
func count(_ store: DatabaseStore, _ table: String) throws -> Int {
    try store.queue.read { db in try Int.fetchOne(db, sql: "SELECT COUNT(*) FROM \(table)") ?? 0 }
}

func pragma(_ store: DatabaseStore, _ name: String) throws -> String? {
    try store.queue.read { db in try String.fetchOne(db, sql: "PRAGMA \(name)") }
}

/// A random UUID-shaped id, for rows inserted with raw SQL.
func rawId() -> String { newId() }

/// The database fixtures in `Fixtures/db`, generated by running the real TypeScript
/// (see `Fixtures/db/README.md`).
enum DatabaseFixtures {
    static var directory: URL {
        get throws {
            try #require(Bundle.module.url(forResource: "db", withExtension: nil, subdirectory: "Fixtures"))
        }
    }

    static func url(_ relativePath: String) throws -> URL {
        try directory.appending(path: relativePath, directoryHint: .notDirectory)
    }

    static func decode<T: Decodable>(_ type: T.Type, from relativePath: String) throws -> T {
        try JSONDecoder().decode(type, from: Data(contentsOf: url(relativePath)))
    }

    /// Copies a fixture database (and the named sidecars, e.g. `-wal`) into `scratch` as
    /// `inventory.db`, so opening it never touches the bundle; returns the copy's path.
    static func copy(_ relativePath: String, sidecars: [String] = [], into scratch: TemporaryDirectory) throws -> String {
        let destination = scratch.path(DatabaseStore.fileName)
        try FileManager.default.copyItem(at: url(relativePath), to: URL(fileURLWithPath: destination))
        for suffix in sidecars {
            try FileManager.default.copyItem(
                at: url(relativePath + suffix),
                to: URL(fileURLWithPath: destination + suffix)
            )
        }
        return destination
    }
}

/// A JSON scalar as node:sqlite returned it, compared with exact code points.
enum SQLScalar: Decodable, Equatable, CustomStringConvertible {
    case null
    case int(Int64)
    case double(Double)
    case string(String)

    init(from decoder: any Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
        } else if let value = try? container.decode(Int64.self) {
            self = .int(value)
        } else if let value = try? container.decode(Double.self) {
            self = .double(value)
        } else {
            self = .string(try container.decode(String.self))
        }
    }

    init(_ value: DatabaseValue) {
        switch value.storage {
        case .null: self = .null
        case .int64(let int): self = .int(int)
        case .double(let double): self = .double(double)
        case .string(let string): self = .string(string)
        case .blob(let data): self = .string("<blob \(data.count) bytes>")
        }
    }

    static func == (lhs: SQLScalar, rhs: SQLScalar) -> Bool {
        switch (lhs, rhs) {
        case (.null, .null): true
        case let (.int(a), .int(b)): a == b
        case let (.double(a), .double(b)): a == b
        case let (.string(a), .string(b)): a.utf8.elementsEqual(b.utf8)
        default: false
        }
    }

    var description: String {
        switch self {
        case .null: "null"
        case .int(let value): "\(value)"
        case .double(let value): "\(value)"
        case .string(let value): "\"\(value)\""
        }
    }
}

typealias ScalarRow = [String: SQLScalar]

/// Every row of `table` in rowid order, as column → value.
func dumpTable(_ db: Database, _ table: String) throws -> [ScalarRow] {
    try Row.fetchAll(db, sql: "SELECT * FROM \"\(table)\" ORDER BY rowid").map { row in
        var out: ScalarRow = [:]
        for (column, value) in row {
            out[column] = SQLScalar(value)
        }
        return out
    }
}

/// The user tables in creation order (no `sqlite_*` tables).
func userTables(_ db: Database) throws -> [String] {
    try String.fetchAll(
        db,
        sql: "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
    )
}

/// One row of `sqlite_master`, without `rootpage`.
struct MasterRow: Decodable, Equatable, CustomStringConvertible {
    let type: String
    let name: String
    let tbl_name: String
    let sql: String?

    static func == (lhs: MasterRow, rhs: MasterRow) -> Bool {
        lhs.type == rhs.type && lhs.name == rhs.name && lhs.tbl_name == rhs.tbl_name
            && lhs.sql.map { Array($0.utf8) } == rhs.sql.map { Array($0.utf8) }
    }

    var description: String { "\(type) \(name) on \(tbl_name): \(sql ?? "NULL")" }
}

func sqliteMaster(_ db: Database) throws -> [MasterRow] {
    try Row.fetchAll(db, sql: "SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY rowid").map { row in
        MasterRow(
            type: try row.decode(forColumn: "type"),
            name: try row.decode(forColumn: "name"),
            tbl_name: try row.decode(forColumn: "tbl_name"),
            sql: try row.decode(forColumn: "sql")
        )
    }
}

