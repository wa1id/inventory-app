/// A value behind a lock, shareable with `@Sendable` closures.
final class Locked<Value: Sendable>: Sendable {
    private let mutex: Mutex<Value>

    init(_ value: Value) {
        mutex = Mutex(value)
    }

    var value: Value {
        mutex.withLock { $0 }
    }

    @discardableResult
    func update<Result: Sendable>(_ body: (inout Value) -> Result) -> Result {
        mutex.withLock { value in body(&value) }
    }
}

/// A clock that ticks by one millisecond on every read, for deterministic ordering.
final class TickingClock: Sendable {
    private let current: Locked<Int64>

    init(start: Int64 = 1_700_000_000_000) {
        current = Locked(start)
    }

    func now() -> Int64 {
        current.update { value in
            value += 1
            return value
        }
    }
}
