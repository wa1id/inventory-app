function argumentSets(node) {
  const values = node.params.length === 1 ? VALUES.single : VALUES.several;
  let sets = [{}];
  for (const p of node.params) {
    let options = values[p.type];
    if (p.type === 'string' && EXTRA_STRINGS[node.path]) options = [...options, ...EXTRA_STRINGS[node.path]()];
    sets = sets.flatMap((set) => options.map((v) => ({ ...set, [p.name]: v })));
  }
  return sets;
}

const callNode = (node, set) => node.fn(...node.params.map((p) => set[p.name]));

