function unwrap(node) {
  let n = node;
  while (ts.isAsExpression(n) || ts.isParenthesizedExpression(n) || ts.isSatisfiesExpression(n)) {
    n = n.expression;
  }
  return n;
}

function isRecordCast(node) {
  let n = node;
  while (ts.isParenthesizedExpression(n)) n = n.expression;
  return (
    (ts.isAsExpression(n) || ts.isSatisfiesExpression(n)) &&
    ts.isTypeReferenceNode(n.type) &&
    n.type.typeName.getText() === 'Record'
  );
}

function propertyName(property) {
  const n = property.name;
  if (ts.isIdentifier(n) || ts.isStringLiteral(n) || ts.isNumericLiteral(n)) return n.text;
  return fail(`unsupported property name ${n.getText()}`);
}

function docComment(node, text) {
  const ranges = ts.getLeadingCommentRanges(text, node.getFullStart()) ?? [];
  const docs = ranges
    .map((r) => text.slice(r.pos, r.end))
    .filter((c) => c.startsWith('/**'))
    .map((c) =>
      c
        .replace(/^\/\*\*/, '')
        .replace(/\*\/$/, '')
        .split('\n')
        .map((line) => line.replace(/^\s*\*?\s?/, '').trim())
        .filter(Boolean)
        .join(' '),
    );
  return docs.join(' ') || undefined;
}

const PARAM_TYPES = {
  [ts.SyntaxKind.NumberKeyword]: 'number',
  [ts.SyntaxKind.StringKeyword]: 'string',
  [ts.SyntaxKind.BooleanKeyword]: 'boolean',
};

/**
 * The tree of one source file (strings.ts or a native file): `value` is its
 * evaluated `strings` object, `origin` names the file in messages.
 */
function readTree(file, value, origin) {
  const text = fs.readFileSync(file, 'utf8');
  const sourceFile = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  let root;
  for (const statement of sourceFile.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (declaration.name.getText() === 'strings') root = unwrap(declaration.initializer);
    }
  }
  if (!root || !ts.isObjectLiteralExpression(root)) fail(`${origin}: could not find \`export const strings = { … }\``);

  function walk(objectNode, value, parts) {
    const children = [];
    const seen = new Set();
    for (const property of objectNode.properties) {
      if (!ts.isPropertyAssignment(property)) {
        fail(`${parts.join('.') || 'strings'}: only plain properties are supported (${property.getText().slice(0, 40)})`);
      }
      const name = propertyName(property);
      seen.add(name);
      const childPath = [...parts, name];
      const pathText = childPath.join('.');
      const doc = docComment(property, text);
      const init = property.initializer;
      const node = unwrap(init);
      const v = value[name];
      if (isRecordCast(init) || LOOKUP_GROUPS.has(pathText)) {
        if (!ts.isObjectLiteralExpression(node)) fail(`${pathText}: a Record cast must wrap an object literal`);
        const entries = node.properties.map((p) => {
          const key = propertyName(p);
          if (typeof v[key] !== 'string') fail(`${pathText}.${key} is not a string`);
          return { key, value: v[key], doc: docComment(p, text) };
        });
        children.push({ kind: 'map', name, path: pathText, doc, entries });
      } else if (ts.isObjectLiteralExpression(node)) {
        children.push({ kind: 'group', name, path: pathText, doc, children: walk(node, v, childPath) });
      } else if (ts.isArrayLiteralExpression(node)) {
        if (!Array.isArray(v) || v.some((s) => typeof s !== 'string')) fail(`${pathText} must be an array of strings`);
        children.push({ kind: 'list', name, path: pathText, doc, values: [...v] });
      } else if (ts.isArrowFunction(node) || ts.isFunctionExpression(node)) {
        const params = node.parameters.map((p) => {
          const type = p.type && PARAM_TYPES[p.type.kind];
          if (!ts.isIdentifier(p.name) || !type || p.initializer || p.dotDotDotToken) {
            fail(`${pathText}: parameter ${p.getText()} must be a plain number, string or boolean`);
          }
          return { name: p.name.text, type };
        });
        if (typeof v !== 'function') fail(`${pathText} did not evaluate to a function`);
        children.push({ kind: 'func', name, path: pathText, doc, params, fn: v });
      } else {
        if (typeof v !== 'string') fail(`${pathText}: unsupported value ${node.getText().slice(0, 40)}`);
        children.push({ kind: 'text', name, path: pathText, doc, value: v });
      }
    }
    for (const key of Object.keys(value)) {
      if (!seen.has(key)) fail(`${origin}: ${[...parts, key].join('.')} exists at runtime but not in the source`);
    }
    for (const child of children) child.origin = origin;
    return children;
  }

  return walk(root, value, []);
}

const tree = readTree(SOURCES.strings, strings, 'src/i18n/strings.ts');

/**
 * Merges a native file's tree into `into`: its groups join the groups of the
 * same path (`backup` → strings.ts's `backup`), everything else must be new.
 */
function mergeTree(into, extra, origin) {
  for (const node of extra) {
    const existing = into.find((child) => child.name === node.name);
    if (!existing) {
      into.push(node);
    } else if (existing.kind === 'group' && node.kind === 'group') {
      mergeTree(existing.children, node.children, origin);
    } else {
      fail(`${origin}: ${node.path} already exists in ${existing.origin}; native copy may only add new keys`);
    }
  }
}

/** Marks every native entry in its doc comment, so the catalog and L10n say where it lives. */
function noteNative(children, origin) {
  for (const node of children) {
    if (node.kind === 'group') {
      noteNative(node.children, origin);
    } else {
      node.doc = [node.doc, `Native only (${origin}).`].filter(Boolean).join(' ');
    }
  }
}

