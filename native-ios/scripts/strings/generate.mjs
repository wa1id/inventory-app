/** Transpiles and runs a TS module; `expose` also exports module-private functions as `__<name>`. */
function evaluate(file, imports, expose = []) {
  const source = fs.readFileSync(file, 'utf8') + expose.map((name) => `\nexport { ${name} as __${name} };`).join('');
  const { outputText } = ts.transpileModule(source, {
    fileName: file,
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  const module = { exports: {} };
  const requireShim = (id) => {
    if (Object.hasOwn(imports, id)) return imports[id];
    throw new Error(`${path.relative(REPO, file)} imports ${id}, which generate.mjs does not provide`);
  };
  new Function('exports', 'require', 'module', outputText)(module.exports, requireShim, module);
  return module.exports;
}

