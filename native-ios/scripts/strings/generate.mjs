const SWIFT_KEYWORDS = new Set(
  ('associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private ' +
    'precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default ' +
    'defer do else fallthrough for guard if in repeat return throw switch where while Any as await false is nil self ' +
    'Self super throws true try _').split(' '),
);
const isIdentifier = (s) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(s);
const swiftIdent = (s) => {
  if (!isIdentifier(s)) fail(`${s} is not a valid Swift identifier`);
  return SWIFT_KEYWORDS.has(s) ? `\`${s}\`` : s;
};
const upperCamel = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const SWIFT_TYPES = { number: 'Int', string: 'String', boolean: 'Bool' };

function swiftString(s) {
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\t') out += '\\t';
    else if (ch === '\r') out += '\\r';
    else if (cp < 0x20 || cp === 0x7f || INVISIBLE.has(cp)) out += `\\u{${cp.toString(16).toUpperCase().padStart(4, '0')}}`;
    else out += ch;
  }
  return `${out}"`;
}

/** Doc line: the English with `{param}` where an argument goes (plural: the other form). */
function englishDoc(entry, node) {
  const name = (n) => `{${n}}`;
  switch (entry.kind) {
    case 'text':
      return JSON.stringify(entry.value);
    case 'format':
    case 'plural':
    case 'subst': {
      const params = node ? node.params : [];
      const types = Object.fromEntries(params.map((p) => [p.name, p.type]));
      const values = Object.fromEntries((entry.args ?? []).map((a) => [a, types[a] === 'number' ? 7 : name(a)]));
      let text = renderEntry(entry, values);
      for (const a of entry.args ?? []) if (types[a] === 'number') text = text.replace(/(?<!\d)7(?!\d)/, name(a));
      return JSON.stringify(text);
    }
    default:
      return '';
  }
}

function docLines(indent, ...lines) {
  return lines
    .filter(Boolean)
    .map((line) => `${indent}/// ${line.replace(/\n/g, ' ')}`)
    .join('\n');
}

function runtimeCall(key, entry) {
  const args = (entry.args ?? []).map(swiftIdent);
  switch (entry.kind) {
    case 'text':
      return `L10nRuntime.text(${swiftString(key)}, ${swiftString(entry.value)})`;
    case 'format':
      return `L10nRuntime.format(${swiftString(key)}, ${swiftString(entry.value)}, [${args.join(', ')}])`;
    case 'plural':
      return `L10nRuntime.plural(${swiftString(key)}, one: ${swiftString(entry.one)}, other: ${swiftString(entry.other)}, ${args[0]})`;
    case 'subst': {
      const subs = entry.subs
        .map((s) => `.init(${swiftString(s.name)}, ${s.argNum}, one: ${swiftString(s.one)}, other: ${swiftString(s.other)})`)
        .join(', ');
      return `L10nRuntime.substitutions(${swiftString(key)}, ${swiftString(entry.value)}, [${subs}], [${args.join(', ')}])`;
    }
    default:
      return fail(`unknown entry kind ${entry.kind}`);
  }
}

/** A member that resolves one catalog entry: a static var, or a static func taking `params`. */
function entryMember(indent, access, name, key, entry, params, doc) {
  const prefix = access ? `${access} ` : '';
  const lines = [docLines(indent, ...doc)];
  if (params.length === 0) {
    lines.push(`${indent}${prefix}static var ${swiftIdent(name)}: String { ${runtimeCall(key, entry)} }`);
  } else {
    const signature = params.map((p) => `${swiftIdent(p.name)}: ${SWIFT_TYPES[p.type]}`).join(', ');
    lines.push(`${indent}${prefix}static func ${swiftIdent(name)}(${signature}) -> String {`);
    lines.push(`${indent}    ${runtimeCall(key, entry)}`);
    lines.push(`${indent}}`);
  }
  return lines.filter(Boolean).join('\n');
}

function paramsUsed(entry, node) {
  const used = new Set(entry.args ?? []);
  return node.params.filter((p) => used.has(p.name));
}

function swiftSignature(node) {
  return `${node.name}(${node.params.map((p) => `${p.name}:`).join('')})`;
}

function emitGroup(children, indent) {
  const blocks = [];
  for (const node of children) {
    switch (node.kind) {
      case 'text':
        blocks.push(entryMember(indent, 'public', node.name, node.path, catalog.get(node.path), [], [node.doc, englishDoc(catalog.get(node.path))]));
        break;
      case 'list': {
        const items = node.values.map((_, i) => `${indent}    ${runtimeCall(`${node.path}.${i}`, catalog.get(`${node.path}.${i}`))},`);
        blocks.push(
          [docLines(indent, node.doc, `${node.values.length} strings, in strings.ts order.`), `${indent}public static var ${swiftIdent(node.name)}: [String] {`, `${indent}    [`, ...items.map((l) => `    ${l}`), `${indent}    ]`, `${indent}}`]
            .filter(Boolean)
            .join('\n'),
        );
        break;
      }
      case 'map': {
        const inner = `${indent}    `;
        const lines = [docLines(indent, node.doc, `Lookup map (\`strings.${node.path}[key]\`).`), `${indent}public enum ${upperCamel(node.name)} {`];
        const memberOf = new Map();
        for (const e of node.entries) {
          if (isIdentifier(e.key) && e.key !== 'allKeys') {
            lines.push(entryMember(inner, 'public', e.key, e.catalogKey, catalog.get(e.catalogKey), [], [e.doc, englishDoc(catalog.get(e.catalogKey))]));
            memberOf.set(e.key, swiftIdent(e.key));
          }
        }
        lines.push(`${inner}/// The keys, in strings.ts order.`);
        lines.push(`${inner}public static let allKeys: [String] = [${node.entries.map((e) => swiftString(e.key)).join(', ')}]`);
        lines.push(`${inner}/// The value for \`key\`, or nil when strings.ts has no such key. The match is exact, as in JS.`);
        lines.push(`${inner}public static subscript(key: String) -> String? {`);
        for (const e of node.entries) {
          const value = memberOf.get(e.key) ?? runtimeCall(e.catalogKey, catalog.get(e.catalogKey));
          lines.push(`${inner}    if L10nRuntime.same(key, ${swiftString(e.key)}) { return ${value} }`);
        }
        lines.push(`${inner}    return nil`);
        lines.push(`${inner}}`);
        lines.push(`${indent}}`);
        blocks.push(lines.filter(Boolean).join('\n'));
        break;
      }
      case 'func': {
        const plan = planned.get(node.path);
        if (plan.generated) {
          blocks.push(entryMember(indent, 'public', node.name, node.path, plan.entry, node.params, [node.doc, englishDoc(plan.entry, node)]));
          break;
        }
        const inner = `${indent}    `;
        const lines = [`${indent}/// Catalog entries behind \`${swiftSignature(node)}\` (composed in L10n+Logic.swift).`, `${indent}enum ${upperCamel(node.name)}Keys {`];
        if (plan.perType) {
          const { template, perType } = plan.perType;
          lines.push(entryMember(inner, '', 'base', node.path, template, paramsUsed(template, node), [englishDoc(template, node)]));
          lines.push(`${inner}/// The entry for a known visual type (a key of entities.typeNames), or nil.`);
          lines.push(`${inner}static func perType(_ visualType: String) -> String? {`);
          for (const t of perType) {
            lines.push(`${inner}    if L10nRuntime.same(visualType, ${swiftString(t.type)}) { return ${runtimeCall(t.key, catalog.get(t.key))} }`);
          }
          lines.push(`${inner}    return nil`);
          lines.push(`${inner}}`);
        }
        for (const c of plan.cases ?? []) {
          if (c.reuse) continue;
          lines.push(entryMember(inner, '', c.suffix || 'base', c.key, c.entry, paramsUsed(c.entry, node), [englishDoc(c.entry, node)]));
        }
        lines.push(`${indent}}`);
        const hasMembers = plan.perType || (plan.cases ?? []).some((c) => !c.reuse);
        if (hasMembers) blocks.push(lines.join('\n'));
        break;
      }
      case 'group': {
        blocks.push(
          [docLines(indent, node.doc), `${indent}public enum ${upperCamel(node.name)} {`, emitGroup(node.children, `${indent}    `), `${indent}}`]
            .filter(Boolean)
            .join('\n'),
        );
        break;
      }
      default:
        fail(`unknown node kind ${node.kind}`);
    }
  }
  return blocks.join('\n\n');
}

function checkSwiftNames(children, scope) {
  const names = new Map();
  const claim = (name, what) => {
    if (names.has(name)) fail(`${scope}: ${what} clashes with ${names.get(name)} in Swift`);
    names.set(name, what);
  };
  for (const node of children) {
    if (node.kind === 'group' || node.kind === 'map') claim(upperCamel(node.name), node.path);
    else claim(node.name, node.path);
    if (node.kind === 'func' && !planned.get(node.path).generated) claim(`${upperCamel(node.name)}Keys`, `${node.path} (keys)`);
    if (node.kind === 'group') checkSwiftNames(node.children, node.path);
  }
}
