const catalog = new Map();
function addKey(key, entry, comment) {
  if (catalog.has(key)) fail(`duplicate catalog key ${key}`);
  catalog.set(key, { ...entry, key, comment });
}

function argumentNote(entry, params) {
  if (!entry.args || entry.args.length === 0) return undefined;
  const types = Object.fromEntries(params.map((p) => [p.name, p.type]));
  const unique = [...new Set(entry.args)];
  return `Arguments: ${unique.map((name) => `${name} (${types[name] === 'number' ? 'count' : 'text'})`).join(', ')}.`;
}

function joinComment(...parts) {
  const text = parts.filter(Boolean).join(' ');
  return text || undefined;
}

function verifyEntry(entry, node, matches, transformArgs, where) {
  let checked = 0;
  for (const set of argumentSets(node)) {
    if (!matches(set)) continue;
    const expected = callNode(node, set);
    const actual = renderEntry(entry, transformArgs ? transformArgs(set) : set);
    if (actual !== expected) {
      fail(`${where}: the derived entry renders ${JSON.stringify(actual)} for ${JSON.stringify(set)}, strings.ts says ${JSON.stringify(expected)}`);
    }
    checked++;
  }
  return checked;
}

/** Derives the catalog entries for one function; returns a description for the Swift emitter. */
function planFunction(node) {
  const plan = PLANS[node.path];
  if (!plan) {
    const entry = derive(node.fn, node.params, {}, node.path);
    verifyEntry(entry, node, () => true, null, node.path);
    addKey(node.path, entry, joinComment(node.doc, argumentNote(entry, node.params)));
    return { generated: true, entry };
  }

  if (plan.perType) {
    const map = nodesByPath.get(plan.perType);
    const transform = TRANSFORMS[plan.transform];
    const template = derive(node.fn, node.params, {}, node.path);
    if (template.kind !== 'format' || template.args.length !== 1) fail(`${node.path}: expected a one-argument template`);
    const param = template.args[0];
    verifyEntry(template, node, () => true, (set) => ({ ...set, [param]: transform(set[param]) }), node.path);
    addKey(
      node.path,
      template,
      joinComment(node.doc, `Template for a type name not in ${plan.perType}, which is passed ${plan.transform === 'lowercase' ? 'lower-cased' : 'transformed'}.`, argumentNote(template, node.params)),
    );
    const perType = map.entries.map(({ key, value }) => {
      const text = node.fn(value);
      addKey(`${node.path}.${key}`, { kind: 'text', value: text }, joinComment(node.doc, `For the ${key} type (${value}).`));
      return { type: key, key: `${node.path}.${key}`, value: text };
    });
    return { generated: false, perType: { template, perType, param } };
  }

  const cases = [];
  for (const c of plan.cases) {
    const fixed = c.fixed ?? {};
    const matches = (set) => Object.entries(fixed).every(([k, v]) => set[k] === v) && (c.when ? c.when(set) : true);
    if (c.reuse) {
      const target = nodesByPath.get(c.reuse);
      if (!target) fail(`${node.path}: reuse target ${c.reuse} does not exist`);
      for (const set of argumentSets(node)) {
        if (!matches(set)) continue;
        const expected = callNode(node, set);
        const actual = target.kind === 'text' ? target.value : target.fn(...node.params.map((p) => set[p.name]));
        if (actual !== expected) fail(`${node.path}: ${c.reuse} gives ${JSON.stringify(actual)} for ${JSON.stringify(set)}, not ${JSON.stringify(expected)}`);
      }
      cases.push({ reuse: c.reuse, matches });
      continue;
    }
    const where = c.suffix ? `${node.path}.${c.suffix}` : node.path;
    const entry = derive(node.fn, node.params, fixed, where);
    const checked = verifyEntry(entry, node, matches, null, where);
    if (checked === 0) fail(`${where}: no test arguments reach this case`);
    const condition = Object.entries(fixed)
      .map(([k, v]) => `${k} = ${v}`)
      .join(', ');
    addKey(where, entry, joinComment(node.doc, condition ? `When ${condition}.` : undefined, argumentNote(entry, node.params)));
    cases.push({ suffix: c.suffix, key: where, entry, matches });
  }
  if (plan.cases.length > 0) {
    for (const set of argumentSets(node)) {
      const hits = cases.filter((c) => c.matches(set)).length;
      if (hits !== 1) fail(`${node.path}: ${hits} cases match ${JSON.stringify(set)}; the plan must cover each exactly once`);
    }
  }
  return { generated: false, cases };
}

// The tree with catalog keys, plus the fixture entries.
const fixtureEntries = [];
const planned = new Map();

function encodeArg(type, value) {
  if (type === 'number') return { int: value };
  if (type === 'boolean') return { bool: value };
  return { string: value };
}

for (const node of nodesByPath.values()) {
  switch (node.kind) {
    case 'group':
      break;
    case 'text':
      addKey(node.path, { kind: 'text', value: node.value }, node.doc);
      fixtureEntries.push({ path: node.path, kind: 'text', cases: [{ args: [], expected: node.value }] });
      break;
    case 'list':
      node.values.forEach((value, i) => addKey(`${node.path}.${i}`, { kind: 'text', value }, joinComment(node.doc, `Item ${i + 1} of ${node.values.length}.`)));
      fixtureEntries.push({
        path: node.path,
        kind: 'list',
        cases: [
          ...node.values.map((value, i) => ({ args: [{ int: i }], expected: value })),
          { args: [{ int: node.values.length }], expected: null },
        ],
      });
      break;
    case 'map': {
      const segmentOf = MAP_SEGMENTS[node.path] ?? ((key) => {
        if (!/^[A-Za-z0-9_]+$/.test(key)) fail(`${node.path}: key ${JSON.stringify(key)} needs an entry in MAP_SEGMENTS`);
        return key;
      });
      const segments = new Set();
      node.entries.forEach((entry) => {
        entry.segment = segmentOf(entry.key, entry.value);
        if (segments.has(entry.segment)) fail(`${node.path}: two keys map to the catalog segment ${entry.segment}`);
        segments.add(entry.segment);
        entry.catalogKey = `${node.path}.${entry.segment}`;
        addKey(entry.catalogKey, { kind: 'text', value: entry.value }, joinComment(node.doc, entry.doc, `Looked up by ${JSON.stringify(entry.key)}.`));
      });
      const misses = new Set(['', 'unknown', 'Box', '#5b8def', '🛋', ' 🚗', 'RATE_LIMITED']);
      for (const { key } of node.entries) misses.delete(key);
      fixtureEntries.push({
        path: node.path,
        kind: 'map',
        cases: [
          ...node.entries.map((e) => ({ args: [{ string: e.key }], expected: e.value })),
          ...[...misses].map((key) => ({ args: [{ string: key }], expected: null })),
        ],
      });
      break;
    }
    case 'func': {
      planned.set(node.path, planFunction(node));
      fixtureEntries.push({
        path: node.path,
        kind: 'function',
        params: node.params.map((p) => `${p.name}: ${p.type}`),
        cases: argumentSets(node).map((set) => ({
          args: node.params.map((p) => encodeArg(p.type, set[p.name])),
          expected: callNode(node, set),
        })),
      });
      break;
    }
    default:
      fail(`unknown node kind ${node.kind}`);
  }
}

