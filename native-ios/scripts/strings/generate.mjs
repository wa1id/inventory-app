/**
 * Generates the iOS String Catalog, the typed `L10n` accessors and the parity
 * fixtures from the React Native copy in src/i18n/strings.ts (+ format.ts),
 * plus the native-only copy in native-ios/scripts/strings/native/<area>.ts.
 *
 *   node native-ios/scripts/strings/generate.mjs              write the outputs
 *   node native-ios/scripts/strings/generate.mjs --check      exit 1 if any output is stale
 *   node native-ios/scripts/strings/generate.mjs --validate   build and verify everything, write nothing
 *   … --native-dir <dir>                                      read the native files from <dir> (tests)
 *   … --manifest <file>                                       also write which Swift accessor reads each key (check.mjs)
 *
 * strings.ts stays the source of truth while Android and web still use it
 * (DECISIONS U9) and is never edited for native-only states: those go in one
 * file per area under native/, shaped like strings.ts and merged into the same
 * tree (a key that already exists in strings.ts or another native file fails).
 * The script transpiles the TS files with the repo's TypeScript compiler,
 * evaluates them in memory and walks each `strings` object next to its syntax
 * tree (for parameter names, types and doc comments).
 *
 * Function-valued strings become format strings. The format is derived by
 * calling the real function with sentinel arguments; a count whose value
 * changes the wording (plural(), `count === 1 ? … : …`) becomes a String
 * Catalog plural variation or substitution. Functions with other logic
 * (booleans, zero branches, case transforms) are listed in PLANS below: each
 * branch gets its own catalog key, and the branching itself is hand-written
 * in Sources/InventoryStrings/L10n+Logic.swift. Every derived entry is
 * re-rendered here and compared with the TS output before anything is
 * written. See README.md next to this file.
 */
