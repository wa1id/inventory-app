const INVISIBLE = new Set([0x00a0, 0x00ad, 0x200b, 0x200c, 0x200d, 0x200e, 0x200f, 0x2028, 0x2029, 0x2060, 0xfe0f, 0xfeff]);

function jsonString(s) {
  let out = '';
  for (const ch of JSON.stringify(s)) {
    const cp = ch.codePointAt(0);
    out += INVISIBLE.has(cp) && cp !== 0xfe0f ? `\\u${cp.toString(16).padStart(4, '0')}` : ch;
  }
  return out;
}

function xcodeJson(value, indent = '') {
  if (typeof value === 'string') return jsonString(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((v) => inner + xcodeJson(v, inner)).join(',\n')}\n${indent}]`;
  }
  const keys = Object.keys(value).filter((k) => value[k] !== undefined).sort();
  if (keys.length === 0) return `{\n\n${indent}}`;
  return `{\n${keys.map((k) => `${inner}${jsonString(k)} : ${xcodeJson(value[k], inner)}`).join(',\n')}\n${indent}}`;
}

const unit = (value) => ({ stringUnit: { state: 'translated', value } });
