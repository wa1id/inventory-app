/**
 * A relative-time bucket: the variants are unitsAgo()'s wording, and every count
 * the bucket can show is rendered and compared with ago() itself.
 */
function agoPlural(name, unitWord, unitMs, range) {
  const where = `format.ago.${name}`;
  const sentinel = numberSentinel(0);
  const other = format.__unitsAgo(sentinel, unitWord);
  const parts = other.split(new RegExp(`(?<!\\d)${sentinel}(?!\\d)`));
  if (parts.length !== 2) fail(`${where}: ${JSON.stringify(other)} must show the count once`);
  const entry = {
    kind: 'plural',
    one: oneToFormat(format.__unitsAgo(1, unitWord), '%lld', where, true),
    other: parts.map(escapePercent).join('%lld'),
    args: ['count'],
  };
  for (let count = range[0]; count <= range[1]; count++) {
    const expected = format.ago(NOW - count * unitMs, NOW);
    const actual = renderEntry(entry, { count });
    if (actual !== expected) fail(`${where}: renders ${JSON.stringify(actual)} for ${count}, format.ts says ${JSON.stringify(expected)}`);
  }
  return entry;
}

