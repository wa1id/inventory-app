// ---------------------------------------------------------------------------
// Deriving catalog entries from functions.
// ---------------------------------------------------------------------------

/** Number sentinels never start or end with 1, so a diff against the value 1 stays inside the number. */
const numberSentinel = (i) => 7000002 + 2 * i;
/** String sentinels are private-use characters only: no digits, unchanged by case mapping. */
const stringSentinel = (i) => `${String.fromCharCode(0xe010 + i)}`;

const escapePercent = (s) => s.replace(/%/g, '%%');

function findOccurrences(text, params, sentinels) {
  const found = [];
  for (const p of params) {
    const token = String(sentinels[p.name]);
    let from = 0;
    for (;;) {
      const at = text.indexOf(token, from);
      if (at < 0) break;
      const end = at + token.length;
      const digitAround = p.type === 'number' && (/\d/.test(text[at - 1] ?? '') || /\d/.test(text[end] ?? ''));
      if (!digitAround) found.push({ param: p.name, type: p.type, start: at, end });
      from = end;
    }
  }
  found.sort((a, b) => a.start - b.start);
  for (let i = 1; i < found.length; i++) {
    if (found[i].start < found[i - 1].end) fail(`overlapping arguments in ${JSON.stringify(text)}`);
  }
  return found;
}

/** Turns the rendering for a count of 1 into a format: the standalone "1" becomes `token`. */
function oneToFormat(text, token, where, required) {
  const matches = [...text.matchAll(/(?<!\d)1(?!\d)/g)];
  if (matches.length > 1) fail(`${where}: the singular form ${JSON.stringify(text)} has more than one "1"`);
  if (matches.length === 0) {
    if (required) fail(`${where}: the singular form ${JSON.stringify(text)} does not show the count`);
    return escapePercent(text);
  }
  const at = matches[0].index;
  return escapePercent(text.slice(0, at)) + token + escapePercent(text.slice(at + 1));
}

function specifier(type, position) {
  const conversion = type === 'number' ? 'lld' : '@';
  return position ? `%${position}$${conversion}` : `%${conversion}`;
}

/**
 * Derives one catalog entry from `fn` with some parameters fixed. Returns
 * `{ kind: 'text', value }`, `{ kind: 'format', value, args }`,
 * `{ kind: 'plural', one, other, args }` or `{ kind: 'subst', value, subs, args }`,
 * where `args` are parameter names in the order the format consumes them.
 */
function derive(fn, params, fixed, where) {
  const free = params.filter((p) => !Object.hasOwn(fixed, p.name));
  const flag = free.find((p) => p.type === 'boolean');
  if (flag) {
    fail(
      `${where}: boolean parameter ${flag.name} needs a case in PLANS ` +
        '(in a native file, give each branch its own key and choose between them in Swift instead)',
    );
  }
  const sentinels = {};
  free.forEach((p, i) => {
    sentinels[p.name] = p.type === 'number' ? numberSentinel(i) : stringSentinel(i);
  });
  const call = (overrides = {}) =>
    fn(
      ...params.map((p) =>
        Object.hasOwn(overrides, p.name) ? overrides[p.name] : Object.hasOwn(fixed, p.name) ? fixed[p.name] : sentinels[p.name],
      ),
    );
  const base = call();
  if (typeof base !== 'string') fail(`${where} did not return a string`);
  const occurrences = findOccurrences(base, free, sentinels);
  const stripped = occurrences.reduceRight((s, o) => s.slice(0, o.start) + s.slice(o.end), base);
  if (/[-]/.test(stripped)) fail(`${where}: an argument is transformed or cut (${JSON.stringify(base)})`);

  const plural = [];
  for (const p of free) {
    if (p.type !== 'number' || !occurrences.some((o) => o.param === p.name)) continue;
    const one = call({ [p.name]: 1 });
    const naive = occurrences.reduceRight(
      (s, o) => (o.param === p.name ? s.slice(0, o.start) + '1' + s.slice(o.end) : s),
      base,
    );
    if (one !== naive) plural.push({ param: p.name, one });
  }

  const assemble = (items, token) => {
    let out = '';
    let at = 0;
    items.forEach((item, i) => {
      out += escapePercent(base.slice(at, item.start)) + token(item, i + 1);
      at = item.end;
    });
    return out + escapePercent(base.slice(at));
  };

  if (plural.length === 0) {
    if (occurrences.length === 0) return { kind: 'text', value: base };
    const positional = occurrences.length > 1;
    return {
      kind: 'format',
      value: assemble(occurrences, (o, n) => specifier(o.type, positional ? n : 0)),
      args: occurrences.map((o) => o.param),
    };
  }

  if (occurrences.length === 1) {
    // A single count decides the whole sentence: plural variations.
    return {
      kind: 'plural',
      one: oneToFormat(plural[0].one, '%lld', where, false),
      other: assemble(occurrences, () => '%lld'),
      args: [plural[0].param],
    };
  }

  // Several arguments: each count that changes the wording becomes a substitution
  // covering the stretch of text that differs between its singular and plural.
  const regions = plural.map(({ param, one }) => {
    if (occurrences.filter((o) => o.param === param).length !== 1) {
      fail(`${where}: the count ${param} appears more than once`);
    }
    let prefix = 0;
    while (prefix < base.length && prefix < one.length && base[prefix] === one[prefix]) prefix++;
    let suffix = 0;
    while (
      suffix < base.length - prefix &&
      suffix < one.length - prefix &&
      base[base.length - 1 - suffix] === one[one.length - 1 - suffix]
    ) {
      suffix++;
    }
    const start = prefix;
    const end = base.length - suffix;
    const inside = occurrences.filter((o) => o.start < end && o.end > start);
    if (inside.length !== 1 || inside[0].param !== param || inside[0].start < start || inside[0].end > end) {
      fail(`${where}: cannot isolate the wording that depends on ${param}`);
    }
    const occurrence = inside[0];
    return {
      param,
      start,
      end,
      other: escapePercent(base.slice(start, occurrence.start)) + '%arg' + escapePercent(base.slice(occurrence.end, end)),
      one: oneToFormat(one.slice(prefix, one.length - suffix), '%arg', where, true),
    };
  });
  const items = [
    ...regions.map((r) => ({ ...r, plural: true })),
    ...occurrences
      .filter((o) => !regions.some((r) => o.start >= r.start && o.end <= r.end))
      .map((o) => ({ ...o, plural: false })),
  ].sort((a, b) => a.start - b.start);
  for (let i = 1; i < items.length; i++) {
    if (items[i].start < items[i - 1].end) fail(`${where}: the wording of two counts overlaps`);
  }
  const value = assemble(items, (item, n) => (item.plural ? `%${n}$#@${item.param}@` : specifier(item.type, n)));
  const subs = items
    .map((item, i) => (item.plural ? { name: item.param, argNum: i + 1, one: item.one, other: item.other } : null))
    .filter(Boolean);
  return { kind: 'subst', value, subs, args: items.map((item) => item.param) };
}

/** Renders an entry the way Foundation does with no locale: ungrouped digits, text as is, `one` only for 1. */
function renderEntry(entry, values) {
  const args = (entry.args ?? []).map((name) => values[name]);
  const printf = (fmt) => {
    let next = 0;
    return fmt.replace(/%%|%(?:(\d+)\$)?(lld|@)/g, (match, position) => {
      if (match === '%%') return '%';
      const v = position ? args[Number(position) - 1] : args[next++];
      return String(v);
    });
  };
  switch (entry.kind) {
    case 'text':
      return entry.value;
    case 'format':
      return printf(entry.value);
    case 'plural':
      return printf(args[0] === 1 ? entry.one : entry.other);
    case 'subst':
      return printf(
        entry.value.replace(/%(\d+)\$#@(\w+)@/g, (_, position, name) => {
          const sub = entry.subs.find((s) => s.name === name);
          const variant = args[Number(position) - 1] === 1 ? sub.one : sub.other;
          return variant.replace(/%arg/g, `%${position}$lld`);
        }),
      );
    default:
      return fail(`unknown entry kind ${entry.kind}`);
  }
}

